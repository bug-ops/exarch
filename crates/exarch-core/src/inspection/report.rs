    proptest::proptest! {
        /// The pass reports every unverified item as a Medium issue, so
        /// INCOMPLETE can never sit next to an overall PASS.
        #[test]
        fn prop_incomplete_integrity_never_coexists_with_overall_pass(
            raw in proptest::collection::vec(
                (0..IssueSeverity::ALL.len(), 0..IssueCategory::ALL.len()),
                0..8,
            ),
            requested in proptest::bool::ANY,
        ) {
            let issues = raw
                .into_iter()
                .map(|(severity, category)| {
                    let category = IssueCategory::ALL[category];
                    let severity = IssueSeverity::ALL[severity];
                    let severity = if category == IssueCategory::IntegrityIncomplete {
                        severity.max(IssueSeverity::Medium)
                    } else {
                        severity
                    };
                    issue(severity, category)
                })
                .collect();
            let scope = if requested {
                IntegrityScope::Requested(IntegrityGaps::default())
            } else {
                IntegrityScope::NotRequested
            };

            let report = integrity_report(issues, scope);
            if report.integrity_status() == IntegrityStatus::Incomplete {
                proptest::prop_assert_ne!(report.status(), VerificationStatus::Pass);
            }
        }
    }
