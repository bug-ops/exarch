/// Result of archive verification.
///
/// Generated by `verify_archive()`, contains the result of the security checks
/// performed without extracting files to disk. Payload integrity is checked
/// only when requested through
/// [`VerificationOptions`](crate::VerificationOptions); otherwise
/// `integrity_status()` is [`IntegrityStatus::Skipped`]. Fields are private:
/// the overall, security and integrity statuses are derived from the issue
/// list, so a report can never contradict its own issues.
///
/// # Examples
///
/// ```no_run
/// use exarch_core::SecurityConfig;
/// use exarch_core::VerificationStatus;
/// use exarch_core::verify_archive;
///
/// # fn main() -> Result<(), Box<dyn std::error::Error>> {
/// let config = SecurityConfig::default();
/// let report = verify_archive("archive.tar.gz", &config)?;
///
/// if report.status() == VerificationStatus::Pass {
///     println!("Archive is safe to extract");
/// } else {
///     eprintln!("Security issues found:");
///     for issue in report.issues() {
///         eprintln!("  [{}] {}", issue.severity(), issue.message());
///     }
/// }
/// # Ok(())
/// # }
/// ```
#[derive(Debug, Clone)]
pub struct VerificationReport {
    issues: Vec<VerificationIssue>,
    integrity: IntegrityScope,
    total_entries: usize,
    suspicious_entries: usize,
    total_size: u64,
    format: ArchiveType,
}

impl VerificationReport {
    /// Builds a report by running `issues_for` over every manifest entry.
    ///
    /// Totals and format come from the manifest. An entry counts as
    /// suspicious when it has at least one issue of [`IssueSeverity::Medium`]
    /// or higher. `status() == Pass` holds exactly when no issue is Medium or
    /// higher. Issues are sorted from most to least severe.
    ///
    /// # Examples
    ///
    /// ```
    /// use std::path::PathBuf;
    ///
    /// use exarch_core::ArchiveEntry;
    /// use exarch_core::ArchiveManifest;
    /// use exarch_core::ManifestEntryKind;
    /// use exarch_core::Uncompressed;
    /// use exarch_core::VerificationReport;
    /// use exarch_core::VerificationStatus;
    /// use exarch_core::formats::detect::ArchiveType;
    ///
    /// let mut manifest = ArchiveManifest::new(ArchiveType::Tar);
    /// let kind = ManifestEntryKind::File {
    ///     size: Uncompressed(1),
    /// };
    /// let entry = ArchiveEntry::new(PathBuf::from("a.txt"), kind);
    /// manifest.add_entry(entry)?;
    ///
    /// let report = VerificationReport::from_entry_issues(&manifest, |_| Vec::new());
    /// assert_eq!(report.status(), VerificationStatus::Pass);
    /// assert_eq!(report.total_entries(), 1);
    /// # Ok::<(), exarch_core::ArchiveError>(())
    /// ```
    #[must_use]
    pub fn from_entry_issues<F>(manifest: &ArchiveManifest, issues_for: F) -> Self
    where
        F: FnMut(&ArchiveEntry) -> Vec<VerificationIssue>,
    {
        let lists = manifest.entries().iter().map(issues_for).collect();
        Self::from_entry_issue_lists(
            manifest,
            lists,
            Vec::new(),
            &ArchiveStructure::of_manifest(manifest),
            IntegrityScope::NotRequested,
        )
    }

    /// Builds a report from one precomputed issue list per manifest entry,
    /// issues that belong to the archive as a whole, and the structure of the
    /// archive the manifest came from.
    ///
    /// `lists` holds one list per manifest entry, optionally followed by
    /// lists of archive-level issues. A structural finding bound to an entry
    /// joins that entry's list, so an entry with several issues still counts
    /// once; any other finding is an archive-level list. Only entries count
    /// as suspicious, so `suspicious_entries()` never exceeds the manifest,
    /// while archive-level issues still decide `status()`.
    pub(crate) fn from_entry_issue_lists(
        manifest: &ArchiveManifest,
        mut lists: Vec<Vec<VerificationIssue>>,
        archive_issues: Vec<VerificationIssue>,
        structure: &ArchiveStructure<'_>,
        integrity: IntegrityScope,
    ) -> Self {
        for finding in structure.findings {
            let bound_entry = match finding {
                ZipInconsistency::HeaderMismatch { entry, .. }
                | ZipInconsistency::HeaderUncomparable { entry, .. }
                | ZipInconsistency::DescriptorOverrun { entry, .. }
                | ZipInconsistency::NonRegularPayload { entry, .. }
                | ZipInconsistency::StreamEndUnknown { entry, .. }
                | ZipInconsistency::XlTypeDivergence { entry, .. } => {
                    manifest.position_of_zip_entry(*entry)
                }
                ZipInconsistency::DuplicateName { .. }
                | ZipInconsistency::OverlappingEntries
                | ZipInconsistency::HiddenLocalHeader { .. }
                | ZipInconsistency::IgnoredEndRecord { .. }
                | ZipInconsistency::StrayCentralRecord { .. }
                | ZipInconsistency::StrayEndRecord { .. }
                | ZipInconsistency::UncountedCentralRecords { .. } => None,
            };
            let issue = VerificationIssue::from_error(
                &ArchiveError::ZipInconsistency(finding.clone()),
                None,
            );
            match bound_entry {
                Some(position) => {
                    let issue =
                        issue.with_entry_path(Some(manifest.entries()[position].path.clone()));
                    lists[position].push(issue);
                }
                None => lists.push(vec![issue]),
            }
        }

        if structure.omitted > 0 {
            lists.push(vec![VerificationIssue::new(
                IssueSeverity::Info,
                Finding::Heuristic(Heuristic::OmittedStructureFindings {
                    omitted: structure.omitted,
                }),
            )]);
        }

        let mut issues = archive_issues;
        let mut suspicious_entries = 0;

        for (index, entry_issues) in lists.into_iter().enumerate() {
            if index < manifest.total_entries()
                && entry_issues
                    .iter()
                    .any(|i| i.severity() >= IssueSeverity::Medium)
            {
                suspicious_entries += 1;
            }
            issues.extend(entry_issues);
        }

        issues.sort_by(|a, b| a.severity().cmp(&b.severity()).reverse());

        Self {
            issues,
            integrity,
            total_entries: structure.total_entries,
            suspicious_entries,
            total_size: manifest.total_size(),
            format: manifest.format(),
        }
    }

    /// Returns the overall status, derived from the issue severities.
    #[must_use]
    pub fn status(&self) -> VerificationStatus {
        determine_status(&self.issues)
    }

    /// Returns the security check result, derived from security-category
    /// issues. A [`IssueCategory::NameCollision`] of Low severity (two
    /// directories without contents merging) is reported but not counted.
    #[must_use]
    pub fn security_status(&self) -> CheckStatus {
        determine_security_status(&self.issues)
    }

    /// Returns the integrity check result, derived from the issue list.
    ///
    /// Any [`IssueCategory::CorruptData`] issue gives
    /// [`IntegrityStatus::Fail`]. Otherwise a report built without an
    /// integrity request is [`IntegrityStatus::Skipped`], and a requested check
    /// with an [`IssueCategory::IntegrityIncomplete`] issue is
    /// [`IntegrityStatus::Incomplete`]: some payload was not verified. Only a
    /// requested check with neither is [`IntegrityStatus::Pass`], which for
    /// formats without payload checksums (plain TAR, 7z entries without CRC)
    /// means the data was decodable and complete, not checksum-verified.
    #[must_use]
    pub fn integrity_status(&self) -> IntegrityStatus {
        determine_integrity_status(&self.issues, &self.integrity)
    }

    /// What the requested integrity check left unverified, or `None` when no
    /// integrity check was requested.
    ///
    /// A requested check that verified everything returns an empty
    /// [`IntegrityGaps`].
    #[must_use]
    pub const fn integrity_gaps(&self) -> Option<&IntegrityGaps> {
        match &self.integrity {
            IntegrityScope::Requested(gaps) => Some(gaps),
            IntegrityScope::NotRequested => None,
        }
    }

    /// Returns all issues found, sorted from most to least severe.
    #[must_use]
    pub fn issues(&self) -> &[VerificationIssue] {
        &self.issues
    }

    /// Consumes the report and returns its issues.
    #[must_use]
    pub fn into_issues(self) -> Vec<VerificationIssue> {
        self.issues
    }

    /// Returns the total number of entries scanned.
    #[must_use]
    pub const fn total_entries(&self) -> usize {
        self.total_entries
    }

    /// Returns the number of entries with a Medium-or-higher issue. Issues
    /// that belong to the archive as a whole (a hidden ZIP header, a repeated
    /// name) are not entries and are not counted here, but they fail
    /// [`status`](Self::status).
    #[must_use]
    pub const fn suspicious_entries(&self) -> usize {
        self.suspicious_entries
    }

    /// Returns the total uncompressed size in bytes.
    #[must_use]
    pub const fn total_size(&self) -> u64 {
        self.total_size
    }

    /// Returns the archive format.
    #[must_use]
    pub const fn format(&self) -> ArchiveType {
        self.format
    }

    /// Returns true if the archive is safe (no Medium-or-higher severity
    /// issues).
    #[must_use]
    pub fn is_safe(&self) -> bool {
        self.status() == VerificationStatus::Pass
    }

    /// Returns true if there are any critical severity issues.
    #[must_use]
    pub fn has_critical_issues(&self) -> bool {
        self.issues
            .iter()
            .any(|i| i.severity() == IssueSeverity::Critical)
    }

    /// Returns issues of a specific severity level.
    #[must_use]
    pub fn issues_by_severity(&self, severity: IssueSeverity) -> Vec<&VerificationIssue> {
        self.issues
            .iter()
            .filter(|i| i.severity() == severity)
            .collect()
    }
}

/// What an archive's format reports about its own structure, beyond the
/// manifest of the entries it lists.
#[derive(Debug, Clone, Copy)]
pub(crate) struct ArchiveStructure<'a> {
    total_entries: usize,
    findings: &'a [ZipInconsistency],
    omitted: usize,
    refusals: &'a [VerificationIssue],
}

impl<'a> ArchiveStructure<'a> {
    /// A structure with `total_entries` records and the findings to report.
    pub(crate) const fn new(
        total_entries: usize,
        findings: &'a [ZipInconsistency],
        omitted: usize,
    ) -> Self {
        Self {
            total_entries,
            findings,
            omitted,
            refusals: &[],
        }
    }

    /// Adds archive-level issues for what extraction refuses in the archive.
    pub(crate) const fn with_refusals(mut self, refusals: &'a [VerificationIssue]) -> Self {
        self.refusals = refusals;
        self
    }

    /// Archive-level issues for what extraction refuses in the archive.
    pub(crate) const fn refusals(&self) -> &'a [VerificationIssue] {
        self.refusals
    }

    /// The structure of a format whose manifest is its whole content.
    pub(crate) fn of_manifest(manifest: &ArchiveManifest) -> Self {
        Self::new(manifest.total_entries(), &[], 0)
    }
}

fn determine_status(issues: &[VerificationIssue]) -> VerificationStatus {
    let has_critical = issues
        .iter()
        .any(|i| i.severity() == IssueSeverity::Critical);
    let has_high = issues.iter().any(|i| i.severity() == IssueSeverity::High);
    let has_medium = issues.iter().any(|i| i.severity() == IssueSeverity::Medium);

    if has_critical || has_high {
        VerificationStatus::Fail
    } else if has_medium {
        VerificationStatus::Warning
    } else {
        VerificationStatus::Pass
    }
}

fn determine_integrity_status(
    issues: &[VerificationIssue],
    scope: &IntegrityScope,
) -> IntegrityStatus {
    let has = |category| issues.iter().any(|i| i.category() == category);
    if has(IssueCategory::CorruptData) {
        IntegrityStatus::Fail
    } else if matches!(scope, IntegrityScope::NotRequested) {
        IntegrityStatus::Skipped
    } else if has(IssueCategory::IntegrityIncomplete) {
        IntegrityStatus::Incomplete
    } else {
        IntegrityStatus::Pass
    }
}

/// Whether the caller asked for a payload integrity check, and what the check
/// left unverified.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum IntegrityScope {
    NotRequested,
    Requested(IntegrityGaps),
}

closed_enum! {
    /// Why part of the payload was not verified by the integrity check.
    ///
    /// `#[non_exhaustive]` so a future reason is not a breaking change for
    /// downstream matches. The string form is stable and shared by the CLI
    /// JSON output and the language bindings.
    #[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
    #[non_exhaustive]
    pub enum UnverifiedReason {
        /// The decompression budget could not cover it.
        OverBudget => "over_budget",

        /// Quota, ratio or decoder-memory admission refused it.
        ResourceLimit => "resource_limit",

        /// A solid 7z block while `allow_solid_archives` is off.
        SolidPolicy => "solid_policy",

        /// The stream outgrew its declared size.
        SizeCeiling => "size_ceiling",

        /// A 7z block checksum that the entries do not cover.
        UncoveredBlockCrc => "uncovered_block_crc",

        /// An unsupported or unparseable 7z coder.
        NotDecodable => "not_decodable",

        /// A TAR stream that ends without an end-of-archive marker.
        NoEndMarker => "no_end_marker",

        /// An entry dropped from the manifest because its path exceeds the
        /// host limits.
        PathTooLong => "path_too_long",

        /// The data-descriptor tail of a ZIP entry was not searched.
        DescriptorTail => "descriptor_tail",
    }
}

impl UnverifiedReason {
    /// A short human-readable description, used in report messages.
    #[must_use]
    pub const fn description(self) -> &'static str {
        match self {
            Self::OverBudget => "over budget",
            Self::ResourceLimit => "resource limit",
            Self::SolidPolicy => "solid archive with allow_solid_archives off",
            Self::SizeCeiling => "declared size exceeded",
            Self::UncoveredBlockCrc => "block checksum not reachable",
            Self::NotDecodable => "not decodable",
            Self::NoEndMarker => "no end-of-archive marker",
            Self::PathTooLong => "path too long for the host",
            Self::DescriptorTail => {
                "data-descriptor tail not searched (budget, or raw decode disagrees with the zip crate)"
            }
        }
    }
}

/// Most unverified entries an [`IntegrityGaps`] lists by path; the rest are
/// only counted.
pub(crate) const MAX_LISTED_UNVERIFIED: usize = 256;

/// One entry the integrity check could not verify, and why.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct UnverifiedEntry {
    path: PathBuf,
    reason: UnverifiedReason,
}

impl UnverifiedEntry {
    /// The entry's path inside the archive.
    #[must_use]
    pub fn path(&self) -> &Path {
        &self.path
    }

    /// Why the entry was not verified.
    #[must_use]
    pub const fn reason(&self) -> UnverifiedReason {
        self.reason
    }
}

/// What a requested integrity check left unverified.
///
/// The counts, the listed entries and the `IntegrityIncomplete` issue message
/// all come from this one value, so they cannot disagree. Items that belong to
/// no single entry (a TAR stream without an end marker) are only counted;
/// entries past a fixed cap (256 today; rely on [`omitted`](Self::omitted), not
/// the number) are counted in [`omitted`](Self::omitted) instead of listed. The
/// `counts` shape differs per surface: an iterator in Rust, a map in the CLI
/// JSON, a dict in Python and an array of `{reason, count}` in Node.
///
/// # Examples
///
/// ```no_run
/// use exarch_core::DecompressionBudget;
/// use exarch_core::IntegrityCheck;
/// use exarch_core::SecurityConfig;
/// use exarch_core::VerificationOptions;
/// use exarch_core::VerifyRequest;
///
/// # fn main() -> Result<(), Box<dyn std::error::Error>> {
/// let options = VerificationOptions::default()
///     .with_integrity(IntegrityCheck::DecodeToEof(DecompressionBudget::DEFAULT));
/// let config = SecurityConfig::default();
/// let report = VerifyRequest::new(&config)
///     .with_options(options)
///     .verify("a.7z")?;
/// if let Some(gaps) = report.integrity_gaps() {
///     for (reason, count) in gaps.counts() {
///         println!("{reason}: {count}");
///     }
/// }
/// # Ok(())
/// # }
/// ```
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct IntegrityGaps {
    counts: BTreeMap<UnverifiedReason, u64>,
    entries: Vec<UnverifiedEntry>,
    omitted: u64,
}

impl IntegrityGaps {
    /// Counts of unverified items per reason, in reason order; reasons with no
    /// items are absent.
    pub fn counts(&self) -> impl Iterator<Item = (UnverifiedReason, u64)> + '_ {
        self.counts.iter().map(|(&reason, &count)| (reason, count))
    }

    /// Number of items left unverified for `reason`.
    #[must_use]
    pub fn count(&self, reason: UnverifiedReason) -> u64 {
        self.counts.get(&reason).copied().unwrap_or_default()
    }

    /// Total number of unverified items.
    #[must_use]
    pub fn total(&self) -> u64 {
        self.counts.values().sum()
    }

    /// Returns true when nothing was left unverified.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.counts.is_empty()
    }

    /// The unverified entries that could be listed by path, up to a fixed cap;
    /// further ones are counted in [`omitted`](Self::omitted).
    #[must_use]
    pub fn entries(&self) -> &[UnverifiedEntry] {
        &self.entries
    }

    /// Number of unverified entries that had a path but were not listed
    /// because the list was full.
    #[must_use]
    pub const fn omitted(&self) -> u64 {
        self.omitted
    }

    pub(crate) fn count_items(&mut self, reason: UnverifiedReason, items: u64) {
        if items > 0 {
            *self.counts.entry(reason).or_default() += items;
        }
    }

    pub(crate) fn mark_entry(&mut self, reason: UnverifiedReason, path: &Path) {
        self.count_items(reason, 1);
        if self.entries.len() < MAX_LISTED_UNVERIFIED {
            self.entries.push(UnverifiedEntry {
                path: path.to_path_buf(),
                reason,
            });
        } else {
            self.omitted += 1;
        }
    }

    /// The `IntegrityIncomplete` issue message; `None` when nothing is
    /// unverified.
    pub(crate) fn message(&self) -> Option<String> {
        if self.is_empty() {
            return None;
        }
        let detail = self
            .counts()
            .map(|(reason, count)| format!("{}: {count}", reason.description()))
            .collect::<Vec<_>>()
            .join(", ");
        Some(format!(
            "Integrity check incomplete: {} item(s) not verified ({detail})",
            self.total()
        ))
    }
}

fn determine_security_status(issues: &[VerificationIssue]) -> CheckStatus {
    let mut security_issues = issues
        .iter()
        .filter(|i| i.category().is_security() && !i.is_harmless_collision())
        .peekable();

    if security_issues.peek().is_none() {
        return CheckStatus::Pass;
    }

    let fails = security_issues
        .any(|i| i.severity() == IssueSeverity::Critical || i.severity() == IssueSeverity::High);

    if fails {
        CheckStatus::Fail
    } else {
        CheckStatus::Warning
    }
}

closed_enum! {
    /// Overall verification status.
    ///
    /// Closed by design: a new variant is a breaking change, and every
    /// front end pins [`ALL`](Self::ALL) in a drift test so it cannot go
    /// unnoticed.
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub enum VerificationStatus {
        /// All checks passed
        Pass => "PASS",

        /// One or more checks failed
        Fail => "FAIL",

        /// Checks completed with warnings
        Warning => "WARNING",
    }
}

closed_enum! {
    /// Status of a specific check category.
    ///
    /// Closed by design: a new variant is a breaking change, and every
    /// front end pins [`ALL`](Self::ALL) in a drift test so it cannot go
    /// unnoticed.
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub enum CheckStatus {
        /// Check passed
        Pass => "OK",

        /// Check failed
        Fail => "FAILED",

        /// Check completed with warnings
        Warning => "WARNING",

        /// Check was skipped
        Skipped => "SKIPPED",
    }
}

closed_enum! {
    /// Result of the payload integrity check.
    ///
    /// `#[non_exhaustive]` so a future outcome is not a breaking change for
    /// downstream matches.
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    #[non_exhaustive]
    pub enum IntegrityStatus {
        /// Every payload byte was decoded without error. For formats with
        /// payload checksums this includes the checksum; plain TAR, 7z entries
        /// without CRC and zstd frames without a content checksum carry none.
        Pass => "OK",

        /// A checksum or decoder error proved the payload corrupt.
        Fail => "FAILED",

        /// The check ran but some payload was not verified (budget, resource
        /// limit, solid policy, missing end marker).
        Incomplete => "INCOMPLETE",

        /// The check was not requested.
        Skipped => "SKIPPED",
    }
}

/// Single verification issue.
///
/// Holds the severity, the entry it concerns, and a typed [`Finding`]; the
/// category and the message are derived from the finding, so they cannot
/// disagree with it. Construct with [`VerificationIssue::new`] or
/// [`VerificationIssue::from_error`].
#[derive(Debug, Clone)]
pub struct VerificationIssue {
    severity: IssueSeverity,
    entry_path: Option<PathBuf>,
    finding: Finding,
}

/// What a [`VerificationIssue`] found.
///
/// A refusal keeps the typed [`FfiKind`] of the error extraction would raise,
/// so a front end reads the same code, sub-code and policy setting for a
/// verify finding as for a failed extraction without parsing the message.
///
/// # Examples
///
/// ```
/// use exarch_core::ArchiveError;
/// use exarch_core::ErrorCode;
/// use exarch_core::Finding;
/// use exarch_core::VerificationIssue;
///
/// let error = ArchiveError::PathTraversal {
///     path: "../x".into(),
/// };
/// let issue = VerificationIssue::from_error(&error, None);
/// assert!(matches!(issue.finding(), Finding::Refusal { .. }));
/// assert_eq!(
///     issue.ffi_kind().map(|k| k.code()),
///     Some(ErrorCode::PathTraversal)
/// );
/// ```
#[derive(Debug, Clone)]
#[non_exhaustive]
pub enum Finding {
    /// Extraction would refuse the entry or the archive with this error.
    #[non_exhaustive]
    Refusal {
        /// The category the refusal is reported under.
        category: IssueCategory,
        /// The typed discriminants of the refusing error.
        kind: FfiKind,
        /// Human-readable description.
        message: String,
        /// The permission bits of an [`IssueCategory::InvalidPermissions`]
        /// refusal, as the archive stores them.
        mode: Option<RawMode>,
    },
    /// An observation `verify` makes that extraction does not refuse.
    Heuristic(Heuristic),
}

/// An observation `verify` reports on its own, not as a refusal.
///
/// `#[non_exhaustive]` so a new check is not a breaking change for
/// downstream matches.
#[derive(Debug, Clone, PartialEq, Eq)]
#[non_exhaustive]
pub enum Heuristic {
    /// A regular file with an execute bit set.
    ExecutableFile {
        /// The mode as the archive stores it.
        mode: RawMode,
    },
    /// An entry name with an extension commonly used for executables.
    SuspiciousExtension,
    /// An entry name that is not valid UTF-8, which some filesystems refuse.
    NonUtf8Name,
    /// Two names the host filesystem treats as one.
    #[non_exhaustive]
    NameCollision {
        /// Path of the entry that was there first.
        existing: PathBuf,
        /// Path of the entry that collided with it.
        incoming: PathBuf,
        /// How the two differ, which sets how serious the collision is.
        kind: NameCollisionKind,
    },
    /// Extraction with overwrite enabled would fail at a path an earlier
    /// entry holds; default extraction skips the entry.
    #[non_exhaustive]
    OverwriteConflict {
        /// The destination-relative path of the conflict.
        rel: PathBuf,
        /// What an earlier entry put there.
        occupant: PathOccupant,
    },
    /// Symlinks are allowed but some targets were not read, so they were not
    /// validated.
    UnreadSymlinkTargets {
        /// How many symlink targets were left unread.
        count: usize,
    },
    /// The integrity check could not cover part of the payload.
    IntegrityIncomplete(IntegrityGaps),
    /// A checksum or decoder error proved the payload corrupt.
    CorruptData {
        /// The decoder's description of the failure.
        detail: String,
    },
    /// 7z anti-items were skipped; their deletion markers are not applied.
    AntiItemsSkipped {
        /// How many anti-items the archive holds.
        count: u64,
    },
    /// Further 7z refusals exist beyond those listed.
    OmittedRefusals {
        /// How many refusals were left out.
        omitted: usize,
    },
    /// Further ZIP structure findings exist beyond those listed.
    OmittedStructureFindings {
        /// How many findings were left out.
        omitted: usize,
    },
}

impl Heuristic {
    /// The category this observation is reported under.
    #[must_use]
    pub const fn category(&self) -> IssueCategory {
        match self {
            Self::ExecutableFile { .. } => IssueCategory::ExecutableFile,
            Self::SuspiciousExtension | Self::NonUtf8Name => IssueCategory::SuspiciousPath,
            Self::NameCollision { .. } => IssueCategory::NameCollision,
            Self::OverwriteConflict { .. }
            | Self::OmittedRefusals { .. }
            | Self::OmittedStructureFindings { .. } => IssueCategory::InvalidArchive,
            Self::UnreadSymlinkTargets { .. } => IssueCategory::SecurityPolicy,
            Self::IntegrityIncomplete(_) => IssueCategory::IntegrityIncomplete,
            Self::CorruptData { .. } => IssueCategory::CorruptData,
            Self::AntiItemsSkipped { .. } => IssueCategory::ArchiveNote,
        }
    }

    fn message(&self, entry_path: Option<&Path>) -> String {
        let entry = || entry_path.map(crate::path_text).unwrap_or_default();
        match self {
            Self::ExecutableFile { .. } => format!("Executable file: {}", entry()),
            Self::SuspiciousExtension => format!("Suspicious extension: {}", entry()),
            Self::NonUtf8Name => format!(
                "Entry name is not valid UTF-8; extraction may fail on filesystems that require \
                 UTF-8 names (e.g. APFS, NTFS): {}",
                entry()
            ),
            Self::NameCollision {
                existing, incoming, ..
            } => format!(
                "Names \"{}\" and \"{}\" are the same name on case-insensitive or normalizing \
                 filesystems",
                escaped_path(existing),
                escaped_path(incoming)
            ),
            Self::OverwriteConflict { rel, occupant } => format!(
                "extraction with overwrite fails at {}: an earlier entry is a {} (default \
                 extraction skips this entry)",
                crate::path_text(rel),
                occupant.noun()
            ),
            Self::UnreadSymlinkTargets { count } => {
                let (subject, validated) = if *count == 1 {
                    ("symlink target was", "it was")
                } else {
                    ("symlink targets were", "they were")
                };
                format!(
                    "{count} {subject} not read, so {validated} not validated; entries beneath \
                     or through an unread link are reported as failures (an integrity check with \
                     a decompression budget that covers the link blocks reads the targets)"
                )
            }
            Self::IntegrityIncomplete(gaps) => gaps.message().unwrap_or_default(),
            Self::CorruptData { detail } => format!("Corrupt data: {detail}"),
            Self::AntiItemsSkipped { count } => {
                let noun = if *count == 1 {
                    "anti-item"
                } else {
                    "anti-items"
                };
                format!("{count} 7z {noun} skipped (deletion markers are not applied)")
            }
            Self::OmittedRefusals { omitted } => {
                format!("{omitted} further 7z refusals are not listed")
            }
            Self::OmittedStructureFindings { omitted } => {
                format!("{omitted} further ZIP structure findings are not listed")
            }
        }
    }
}

impl Finding {
    /// The refusal of `error`, reported under `category`.
    fn refusal(category: IssueCategory, error: &ArchiveError, message: String) -> Self {
        let mode = match error {
            ArchiveError::InvalidPermissions { mode, .. } => Some(*mode),
            _ => None,
        };
        Self::Refusal {
            category,
            kind: error.ffi_kind(),
            message,
            mode,
        }
    }
}

/// Spells a path injectively ([`crate::path_text`]) and escapes combining
/// marks and control characters too, so two canonically equivalent names do
/// not read as the same text.
fn escaped_path(path: &Path) -> String {
    let mut out = String::new();
    for ch in crate::path_text(path).chars() {
        if ch == '\\' {
            out.push(ch);
        } else {
            out.extend(ch.escape_debug());
        }
    }
    out
}

fn high_invalid_archive(message: String) -> (IssueSeverity, IssueCategory, String) {
    (IssueSeverity::High, IssueCategory::InvalidArchive, message)
}

/// The issue of a TAR header or stream-tail refusal.
fn tar_framing_issue(error: &ArchiveError) -> (IssueSeverity, IssueCategory, String) {
    match error {
        ArchiveError::TarAmbiguity(finding) => {
            high_invalid_archive(format!("Invalid archive: ambiguous TAR header: {finding}"))
        }
        ArchiveError::TarTrailer(refusal @ TarTrailerRefusal::OverCap { .. }) => (
            IssueSeverity::High,
            IssueCategory::SecurityPolicy,
            format!("Security violation: {}", refusal.reason()),
        ),
        ArchiveError::TarTrailer(refusal) => {
            high_invalid_archive(format!("Invalid archive: {}", refusal.reason()))
        }
        other => high_invalid_archive(other.to_string()),
    }
}

impl VerificationIssue {
    /// The one Low-severity security finding: two directories that merge
    /// without either holding an entry, which changes nothing on disk.
    fn is_harmless_collision(&self) -> bool {
        matches!(
            self.finding,
            Finding::Heuristic(Heuristic::NameCollision {
                kind: NameCollisionKind::Directories,
                ..
            })
        )
    }

    /// Creates an issue with no entry path attached.
    #[must_use]
    pub const fn new(severity: IssueSeverity, finding: Finding) -> Self {
        Self {
            severity,
            entry_path: None,
            finding,
        }
    }

    /// Returns the issue attached to `entry_path`.
    #[must_use]
    pub(crate) fn with_entry_path(mut self, entry_path: Option<PathBuf>) -> Self {
        self.entry_path = entry_path;
        self
    }

    /// Returns how serious the issue is.
    #[must_use]
    pub const fn severity(&self) -> IssueSeverity {
        self.severity
    }

    /// Returns the entry that triggered the issue, if it concerns one.
    #[must_use]
    pub fn entry_path(&self) -> Option<&Path> {
        self.entry_path.as_deref()
    }

    /// Returns what was found.
    #[must_use]
    pub const fn finding(&self) -> &Finding {
        &self.finding
    }

    /// Returns the category, derived from the finding.
    #[must_use]
    pub const fn category(&self) -> IssueCategory {
        match &self.finding {
            Finding::Refusal { category, .. } => *category,
            Finding::Heuristic(heuristic) => heuristic.category(),
        }
    }

    /// Returns the human-readable description, derived from the finding.
    #[must_use]
    pub fn message(&self) -> String {
        match &self.finding {
            Finding::Refusal { message, .. } => message.clone(),
            Finding::Heuristic(heuristic) => heuristic.message(self.entry_path()),
        }
    }

    /// Returns the sub-code of the refusing error, when it has one.
    #[must_use]
    pub fn sub_code(&self) -> Option<crate::SubCode> {
        self.ffi_kind().and_then(FfiKind::sub_code)
    }

    /// Returns the permission bits the finding is about: the mode of an
    /// invalid-permissions refusal or of an executable file, as the archive
    /// stores it.
    #[must_use]
    pub const fn mode(&self) -> Option<RawMode> {
        match &self.finding {
            Finding::Refusal { mode, .. } => *mode,
            Finding::Heuristic(Heuristic::ExecutableFile { mode }) => Some(*mode),
            Finding::Heuristic(_) => None,
        }
    }

    /// Returns the typed discriminants of the refusing error, or `None` for a
    /// [`Heuristic`].
    ///
    /// This is the same value a failed extraction reports, so a front end
    /// emits the code, sub-code and policy setting for a verify issue exactly
    /// as it does for an extract error.
    #[must_use]
    pub const fn ffi_kind(&self) -> Option<&FfiKind> {
        match &self.finding {
            Finding::Refusal { kind, .. } => Some(kind),
            Finding::Heuristic(_) => None,
        }
    }

    /// Creates a verification issue from an extraction error.
    #[must_use]
    pub fn from_error(error: &ArchiveError, entry_path: Option<PathBuf>) -> Self {
        let (severity, category, message) = match error {
            ArchiveError::PathTraversal { path } => (
                IssueSeverity::Critical,
                IssueCategory::PathTraversal,
                format!("Path traversal detected: {}", crate::path_text(path)),
            ),
            ArchiveError::SymlinkEscape { path } => (
                IssueSeverity::Critical,
                IssueCategory::SymlinkEscape,
                format!("Symlink escape: {}", crate::path_text(path)),
            ),
            ArchiveError::HardlinkEscape { path } => (
                IssueSeverity::Critical,
                IssueCategory::HardlinkEscape,
                format!("Hardlink escape: {}", crate::path_text(path)),
            ),
            ArchiveError::ZipBomb(details) => (
                IssueSeverity::Critical,
                IssueCategory::ZipBomb,
                format!("Potential zip bomb: {details}"),
            ),
            ArchiveError::ZipInconsistency(finding) => (
                IssueSeverity::High,
                IssueCategory::from_zip_inconsistency(finding),
                error.to_string(),
            ),
            ArchiveError::QuotaExceeded { resource } => (
                IssueSeverity::High,
                IssueCategory::QuotaExceeded,
                resource.to_string(),
            ),
            ArchiveError::InvalidPermissions { path, mode } => (
                IssueSeverity::Medium,
                IssueCategory::InvalidPermissions,
                format!(
                    "Invalid permissions: {} (mode: {:#o})",
                    crate::path_text(path),
                    mode.get()
                ),
            ),
            ArchiveError::Io(io_err) => (
                IssueSeverity::High,
                IssueCategory::InvalidArchive,
                format!("I/O error: {io_err}"),
            ),
            ArchiveError::InvalidArchive(msg) => (
                IssueSeverity::High,
                IssueCategory::InvalidArchive,
                format!("Invalid archive: {msg}"),
            ),
            ArchiveError::TarAmbiguity(_) | ArchiveError::TarTrailer(_) => tar_framing_issue(error),
            ArchiveError::SecurityViolation { kind } => (
                IssueSeverity::High,
                IssueCategory::SecurityPolicy,
                format!("Security violation: {kind}"),
            ),
            ArchiveError::SourceNotFound { path } => (
                IssueSeverity::High,
                IssueCategory::InvalidArchive,
                format!("Source not found: {}", path.display()),
            ),
            ArchiveError::SourceNotAccessible { path } => (
                IssueSeverity::High,
                IssueCategory::InvalidArchive,
                format!("Source not accessible: {}", path.display()),
            ),
            ArchiveError::OutputExists { path } => (
                IssueSeverity::Medium,
                IssueCategory::InvalidArchive,
                format!("Output already exists: {}", path.display()),
            ),
            ArchiveError::InvalidCompressionLevel { level } => (
                IssueSeverity::Medium,
                IssueCategory::InvalidArchive,
                format!("Invalid compression level: {level}"),
            ),
            ArchiveError::UnknownFormat { path } => (
                IssueSeverity::High,
                IssueCategory::InvalidArchive,
                format!("Unknown format: {}", path.display()),
            ),
            ArchiveError::InvalidConfiguration { setting, problem } => high_invalid_archive(
                format!("Invalid configuration: {}", setting.describe(problem)),
            ),
            ArchiveError::ReaderFormat(reason) => {
                high_invalid_archive(format!("Reader format: {reason}"))
            }
            ArchiveError::PartialExtraction(partial) => {
                return Self::from_error(partial.cause(), entry_path);
            }
        };

        Self {
            severity,
            entry_path,
            finding: Finding::refusal(category, error, message),
        }
    }
}

closed_enum! {
    /// Issue severity levels (ordered from least to most severe for Ord).
    ///
    /// Closed by design: a new variant is a breaking change, and every
    /// front end pins [`ALL`](Self::ALL) in a drift test so it cannot go
    /// unnoticed.
    #[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
    pub enum IssueSeverity {
        /// Informational
        Info => "INFO",

        /// Policy violation
        Low => "LOW",

        /// Security concern
        Medium => "MEDIUM",

        /// Exploitable security issue
        High => "HIGH",

        /// CVE-level vulnerability
        Critical => "CRITICAL",
    }
}

closed_enum! {
    /// Issue categories (maps to security checks).
    ///
    /// `#[non_exhaustive]` so a future security check is not a breaking change
    /// for downstream matches.
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    #[non_exhaustive]
    pub enum IssueCategory {
        /// Path traversal attack
        PathTraversal => "Path Traversal",

        /// Symlink escape attack
        SymlinkEscape => "Symlink Escape",

        /// Hardlink escape attack
        HardlinkEscape => "Hardlink Escape",

        /// Zip bomb (excessive compression)
        ZipBomb => "Zip Bomb",

        /// Invalid or unsafe permissions
        InvalidPermissions => "Invalid Permissions",

        /// Quota exceeded (file count or size)
        QuotaExceeded => "Quota Exceeded",

        /// Entry rejected by the security policy (links disallowed, NUL bytes,
        /// banned component, ...)
        SecurityPolicy => "Security Policy",

        /// Invalid or corrupted archive
        InvalidArchive => "Invalid Archive",

        /// Suspicious path or filename
        SuspiciousPath => "Suspicious Path",

        /// Executable file detected
        ExecutableFile => "Executable File",

        /// A checksum or decoder error proved the payload corrupt
        CorruptData => "Corrupt Data",

        /// Integrity check could not cover part of the payload
        IntegrityIncomplete => "Integrity Incomplete",

        /// ZIP local header disagrees with its central directory record
        HeaderMismatch => "Header Mismatch",

        /// ZIP central directory repeats an entry name
        DuplicateEntry => "Duplicate Entry",

        /// ZIP entry data ranges intersect
        OverlappingEntries => "Overlapping Entries",

        /// ZIP entry that the central directory does not account for
        HiddenEntry => "Hidden Entry",

        /// Two entry names the host filesystem treats as one
        NameCollision => "Name Collision",

        /// Informational note that needs no action, such as 7z anti-items that
        /// are skipped
        ArchiveNote => "Archive Note",
    }
}

impl IssueCategory {
    /// Category under which a ZIP structure finding is reported.
    pub(crate) const fn from_zip_inconsistency(finding: &ZipInconsistency) -> Self {
        match finding {
            ZipInconsistency::HeaderMismatch { .. }
            | ZipInconsistency::HeaderUncomparable { .. } => Self::HeaderMismatch,
            ZipInconsistency::DuplicateName { .. } => Self::DuplicateEntry,
            ZipInconsistency::OverlappingEntries => Self::OverlappingEntries,
            ZipInconsistency::HiddenLocalHeader { .. }
            | ZipInconsistency::StrayCentralRecord { .. }
            | ZipInconsistency::StrayEndRecord { .. }
            | ZipInconsistency::DescriptorOverrun { .. }
            | ZipInconsistency::NonRegularPayload { .. }
            | ZipInconsistency::StreamEndUnknown { .. }
            | ZipInconsistency::XlTypeDivergence { .. }
            | ZipInconsistency::UncountedCentralRecords { .. }
            | ZipInconsistency::IgnoredEndRecord { .. } => Self::HiddenEntry,
        }
    }

    /// Whether issues of this category come from a security check, and so
    /// count towards [`VerificationReport::security_status`].
    ///
    /// The match is exhaustive on purpose: a new category must be classified.
    #[must_use]
    pub const fn is_security(self) -> bool {
        match self {
            Self::PathTraversal
            | Self::SymlinkEscape
            | Self::HardlinkEscape
            | Self::ZipBomb
            | Self::InvalidPermissions
            | Self::QuotaExceeded
            | Self::SecurityPolicy
            | Self::HeaderMismatch
            | Self::DuplicateEntry
            | Self::OverlappingEntries
            | Self::HiddenEntry
            | Self::NameCollision => true,
            Self::InvalidArchive
            | Self::SuspiciousPath
            | Self::ExecutableFile
            | Self::CorruptData
            | Self::IntegrityIncomplete
            | Self::ArchiveNote => false,
        }
    }
}

