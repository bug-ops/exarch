#!/usr/bin/env node
// Release gate for the npm tarball (#1200, #1208, #1225). Gates the exact tarball that gets
// published: pass its path, or pass nothing to pack one into a temp dir. The packed index.js
// must be byte-equal to both the committed index.js and the loader generated from
// napi.targets, and the packed package.json must equal the committed one (#1233), so any
// deviation fails; a sandbox run then checks its behaviour per platform.
// `--write-loader` regenerates the committed index.js (export list kept as committed).
// The package directory is the parent of this script.

import { execFileSync } from 'node:child_process';
import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const packageDir = join(dirname(fileURLToPath(import.meta.url)), '..');
const ALLOWED_FILES = new Set(['package.json', 'index.js', 'index.d.ts', 'README.md']);
const ARCH = { x86_64: 'x64', aarch64: 'arm64' };
const TARGET = /^([a-z0-9_]+)-(apple-darwin|pc-windows-msvc|unknown-linux-gnu)$/;
const OS = {
  'apple-darwin': { platform: 'darwin', abi: '' },
  'pc-windows-msvc': { platform: 'win32', abi: '-msvc' },
  'unknown-linux-gnu': { platform: 'linux', abi: '-gnu' },
};
const EXPORT_LINE = /^module\.exports\.([A-Za-z_$][\w$]*) =(?: |\n {2})addon\.\1;$/gm;
const LINE_WIDTH = 100;

const LOADER_HEADER = `// Generated by \`node scripts/check-package.mjs --write-loader\` from napi.targets in
// package.json and the export list below; do not edit by hand. It never resolves a package
// name, so a platform without a bundled addon fails here instead of loading code from the
// registry. The release gate requires every packed copy to equal the generated text.

`;

const LOADER_BODY = `
// Musl only on positive evidence: a report that exists but names no glibc.
// Runtimes without process.report fall through to the glibc addon require.
function isMusl() {
  let report;
  try {
    report = process.report?.getReport?.();
  } catch {
    return false;
  }
  return report !== undefined && typeof report.header?.glibcVersionRuntime !== 'string';
}

function platformKey() {
  const key = \`\${process.platform}-\${process.arch}\`;
  if (process.platform === 'linux' && isMusl()) {
    throw new Error(\`exarch-rs: unsupported platform \${key}-musl; only glibc Linux is bundled\`);
  }
  return key;
}

function loadAddon() {
  const key = platformKey();
  const load = Object.hasOwn(addons, key) ? addons[key] : undefined;
  if (load === undefined) {
    throw new Error(
      \`exarch-rs: unsupported platform \${key}; supported: \${Object.keys(addons).join(', ')}\`
    );
  }
  try {
    return load();
  } catch (cause) {
    throw new Error(\`exarch-rs: failed to load the addon for \${key}\`, { cause });
  }
}

const addon = loadAddon();

// Explicit assignments keep the named exports visible to ESM \`import {...}\` (cjs-module-lexer).
`;

function targetAddon(triple) {
  const match = TARGET.exec(triple);
  const arch = match && ARCH[match[1]];
  if (arch === undefined) {
    throw new Error(`napi target ${triple} has no known addon file name`);
  }
  const { platform, abi } = OS[match[2]];
  return { platform, arch, file: `exarch-rs.${platform}-${arch}${abi}.node` };
}

function exportNames(committedLoader) {
  return [...committedLoader.matchAll(EXPORT_LINE)].map((match) => match[1]);
}

function exportLine(name) {
  const line = `module.exports.${name} = addon.${name};`;
  return line.length <= LINE_WIDTH ? line : `module.exports.${name} =\n  addon.${name};`;
}

function generateLoader(targets, names) {
  const rows = targets.map(
    ({ platform, arch, file }) => `  '${platform}-${arch}': () => require('./${file}'),\n`
  );
  const table = `const addons = {\n${rows.join('')}};\n`;
  return `${LOADER_HEADER}${table}${LOADER_BODY}${names.map(exportLine).join('\n')}\n`;
}

function tar(args) {
  return execFileSync('tar', args, { encoding: 'utf8', maxBuffer: 64 << 20 });
}

function extract(tarball, into) {
  const entries = tar(['-tzf', tarball]).split('\n').filter(Boolean);
  for (const entry of entries) {
    if (!entry.startsWith('package/') || entry.split('/').includes('..')) {
      throw new Error(`tarball entry ${JSON.stringify(entry)} is outside package/`);
    }
  }
  tar(['-xzf', tarball, '-C', into]);
  return join(into, 'package');
}

function packedFileNames(root, errors) {
  const names = [];
  for (const entry of readdirSync(root, { recursive: true, withFileTypes: true })) {
    if (entry.isDirectory()) {
      continue;
    }
    if (!entry.isFile() || entry.parentPath !== root) {
      errors.push(`packed entry ${entry.name} is not a regular top-level file`);
    }
    names.push(entry.name);
  }
  return names;
}

function runLoader(source, { platform, arch, report }) {
  const requested = [];
  const sandbox = {
    module: { exports: {} },
    process: { platform, arch, report },
    require: (id) => {
      requested.push(id);
      return {};
    },
  };
  let thrown;
  try {
    vm.runInNewContext(source, sandbox, { timeout: 2000 });
  } catch (error) {
    thrown = error;
  }
  return { requested, thrown };
}

const MUSL_REPORT = { getReport: () => ({ header: {} }) };

function checkLoaderBehaviour(source, targets, errors) {
  for (const target of targets.filter((t) => t.platform === 'linux')) {
    const { requested, thrown } = runLoader(source, { ...target, report: MUSL_REPORT });
    if (requested.length !== 0 || !/musl/.test(String(thrown?.message))) {
      errors.push(`loader on musl ${target.arch} must refuse without any require`);
    }
  }
  for (const target of targets) {
    const { requested, thrown } = runLoader(source, target);
    const want = `./${target.file}`;
    if (thrown !== undefined || requested.length !== 1 || requested[0] !== want) {
      errors.push(
        `loader on ${target.platform}-${target.arch} must require exactly ${want}, got ` +
          `${JSON.stringify(requested)}${thrown ? ` and threw ${thrown.message}` : ''}`
      );
    }
  }
  const { requested, thrown } = runLoader(source, { platform: 'freebsd', arch: 'arm64' });
  if (requested.length !== 0 || !/supported:/.test(String(thrown?.message))) {
    errors.push('loader must reject an unsupported platform without any require, listing supported');
  }
}

// Fields `pnpm pack` (the release path) rewrites in the packed package.json; measured empty
// for this package, so the packed file must equal the committed one.
const REWRITTEN_BY_PACK = new Set();

function isRecord(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function differingPaths(packed, committed, path = '') {
  if (isRecord(packed) && isRecord(committed)) {
    const keys = new Set([...Object.keys(packed), ...Object.keys(committed)]);
    return [...keys].flatMap((key) => {
      const here = path === '' ? key : `${path}.${key}`;
      return REWRITTEN_BY_PACK.has(here)
        ? []
        : differingPaths(packed[key], committed[key], here);
    });
  }
  return JSON.stringify(packed) === JSON.stringify(committed) ? [] : [path];
}

function check(tarball) {
  const errors = [];
  const work = mkdtempSync(join(tmpdir(), 'exarch-gate-'));
  try {
    const root = extract(tarball, work);
    const names = packedFileNames(root, errors);

    const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
    const committedPkg = JSON.parse(readFileSync(join(packageDir, 'package.json'), 'utf8'));
    for (const field of differingPaths(pkg, committedPkg)) {
      errors.push(`packed package.json field ${field} differs from the committed package.json`);
    }
    const targets = pkg.napi.targets.map(targetAddon);
    const addons = names.filter((name) => name.endsWith('.node')).sort();
    const wantAddons = targets.map((target) => target.file).sort();
    if (JSON.stringify(addons) !== JSON.stringify(wantAddons)) {
      errors.push(
        `packed addons ${JSON.stringify(addons)} differ from napi.targets ${JSON.stringify(wantAddons)}`
      );
    }
    for (const name of names.filter((n) => !n.endsWith('.node') && !ALLOWED_FILES.has(n))) {
      errors.push(`unexpected packed file ${name}`);
    }
    if (pkg.main !== 'index.js' || !names.includes('index.js')) {
      errors.push(`main ${JSON.stringify(pkg.main)} must be the packed index.js`);
    }

    const packed = readFileSync(join(root, 'index.js'), 'utf8');
    const committed = readFileSync(join(packageDir, 'index.js'), 'utf8');
    if (packed !== committed) {
      errors.push('packed index.js differs from the committed index.js');
    }
    if (packed !== generateLoader(targets, exportNames(committed))) {
      errors.push('packed index.js differs from the loader generated from napi.targets');
    }
    checkLoaderBehaviour(packed, targets, errors);
  } finally {
    rmSync(work, { recursive: true, force: true });
  }
  return errors;
}

function packHere() {
  const dir = mkdtempSync(join(tmpdir(), 'exarch-pack-'));
  const out = execFileSync(
    'npm',
    ['pack', '--json', '--ignore-scripts', '--pack-destination', dir],
    { cwd: packageDir, encoding: 'utf8' }
  );
  return { dir, tarball: join(dir, JSON.parse(out)[0].filename) };
}

function writeLoader() {
  const pkg = JSON.parse(readFileSync(join(packageDir, 'package.json'), 'utf8'));
  const path = join(packageDir, 'index.js');
  const names = exportNames(readFileSync(path, 'utf8'));
  writeFileSync(path, generateLoader(pkg.napi.targets.map(targetAddon), names));
  console.log(`check-package: wrote ${path}`);
}

const argument = process.argv[2];
if (argument === '--write-loader') {
  writeLoader();
  process.exit(0);
}

const packed = argument === undefined ? packHere() : undefined;
let errors;
try {
  errors = check(packed === undefined ? resolve(argument) : packed.tarball);
} finally {
  if (packed !== undefined) {
    rmSync(packed.dir, { recursive: true, force: true });
  }
}
if (errors.length > 0) {
  console.error(errors.map((error) => `check-package: ${error}`).join('\n'));
  process.exit(1);
}
console.log('check-package: ok');
